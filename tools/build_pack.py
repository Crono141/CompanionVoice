"""Build the voice pack: every approved take, in a few fixed pitch/formant variants, as the reference clips the engine
clones from, plus the add-on's Voices.lua that lists them.

  python build_pack.py [--takes DIR] [--deliveries DIR] [--out DIR] [--addon DIR]

--takes       the approved designs and their manifest.json (default ~/Projects/LivingVoices/data/companion_voices)
--deliveries  optional: <take>_<delivery>.flac reference clips in the take's voice (urgent, amused, weary)
--out         where the clips go (default pack/out/voices); they ship in Interface\\AddOns\\CompanionVoice\\voices
--addon       the add-on folder whose Voices.lua is rewritten (default addon/CompanionVoice)

Variants are baked here, onto the reference (Praat Change Gender), never onto the engine's output: shifting the
output was rejected by ear in Living Voices ("audible autotune"). Women's variants only go down (VARIANTS_F). A man's variant that would push him above the highest approved take of
his race is mirrored downwards.
Needs praat-parselmouth and ffmpeg.
"""
import argparse, json, os, subprocess, tempfile
from collections import defaultdict
import parselmouth
from parselmouth.praat import call

HERE = os.path.dirname(os.path.abspath(__file__))
VARIANTS = [(0.0, 1.00), (1.5, 1.03), (-1.5, 0.97)]   # (semitones, formant ratio); variant 0 is the design itself
# Women only go down: Pocket TTS already lifts women's excited lines far above their reference (human woman B: ~330 Hz
# typical, 450+ at the top), and a raised reference took her to 485 Hz, where it sounds autotuned (user, 2026-11-05).
VARIANTS_F = [(0.0, 1.00), (-1.2, 0.98), (-2.5, 0.96)]
MAX_REF_S = 14.0                                       # the engine uses up to 15 s of a reference
DELIVERIES = ['urgent', 'amused', 'weary']

def median_f0(snd, lo, hi):
    return call(snd.to_pitch(pitch_floor=lo, pitch_ceiling=hi), 'Get quantile', 0, 0, 0.5, 'Hertz')

def write_mp3(snd, dst):
    with tempfile.NamedTemporaryFile(suffix='.wav') as t:
        snd.save(t.name, 'WAV')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', t.name, '-t', str(MAX_REF_S), '-ac', '1', '-ar', '24000',
                        '-b:a', '64k', dst], check=True)

def load(path):
    with tempfile.NamedTemporaryFile(suffix='.wav') as t:
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', path, '-ac', '1', '-ar', '24000', t.name], check=True)
        return parselmouth.Sound(t.name)

def main():
    a = argparse.ArgumentParser()
    a.add_argument('--takes', default=os.path.expanduser('~/Projects/LivingVoices/data/companion_voices'))
    a.add_argument('--deliveries', default=None)
    a.add_argument('--out', default=os.path.join(HERE, '..', 'pack', 'out', 'voices'))
    a.add_argument('--addon', default=os.path.join(HERE, '..', 'addon', 'CompanionVoice'))
    o = a.parse_args()
    os.makedirs(o.out, exist_ok=True)
    takes = json.load(open(os.path.join(o.takes, 'manifest.json')))['takes']
    ceiling = defaultdict(float)
    for t in takes: ceiling[t['voice']] = max(ceiling[t['voice']], t['ref_f0'])
    listing = defaultdict(list); have = defaultdict(set)
    for t in takes:
        take = t['file'].rsplit('.', 1)[0]                                  # r2_human_f_b
        voice = t['voice']; female = voice.endswith('_f')
        lo, hi = (100, 600) if female else (60, 400)
        refs = {'neutral': os.path.join(o.takes, t['file'])}
        if o.deliveries:
            for d in DELIVERIES:
                p = os.path.join(o.deliveries, f'{take}_{d}.flac')
                if os.path.exists(p): refs[d] = p
        for d, src in refs.items():
            snd = load(src); med = median_f0(snd, lo, hi)
            for k, (st, fm) in enumerate(VARIANTS_F if female else VARIANTS):
                if k and st > 0 and t['ref_f0'] * 2 ** (st / 12) > ceiling[voice] * 1.02: st, fm = -abs(st) * 2, min(fm, 2 - fm)
                out = snd if not k else call(snd, 'Change gender', lo, hi, float(fm), float(med * 2 ** (st / 12)), 1.0, 1.0)
                write_mp3(out, os.path.join(o.out, f'{take}_{k}_{d}.mp3'))
            have[take].add(d)
        listing[voice].append(take)
        print(f'{take}: {len(VARIANTS)} variants x {sorted(have[take])}', flush=True)
    lines = ['-- Generated by tools/build_pack.py: the voice pack. Do not edit by hand.',
             'CompanionVoiceVoices = {', f'  variants = {len(VARIANTS)},', '  takes = {']
    for voice in sorted(listing):
        lines.append(f'    {voice} = {{ ' + ', '.join(f'"{x}"' for x in sorted(listing[voice])) + ' },')
    lines += ['  },', '  deliveries = {']
    for take in sorted(have):
        lines.append(f'    {take} = {{ ' + ', '.join(f'{d} = true' for d in sorted(have[take])) + ' },')
    lines += ['  },', '}', '']
    open(os.path.join(o.addon, 'Voices.lua'), 'w').write('\n'.join(lines))
    print(f'{sum(len(v) for v in listing.values())} takes, {sum(len(v) for v in have.values()) * len(VARIANTS)} clips')

if __name__ == '__main__':
    main()
