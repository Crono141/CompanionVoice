"""The pronunciation guide for the add-on: Living Voices' respellings (data/pronounce.json) as Pronounce.lua.

  python build_pronounce.py [--guide PATH] [--addon DIR]

Taken from the guide: 'words' (whole-word respellings, e.g. Defias -> Defy us, Dalaran -> Dahlarawn), '_suffix'
('*shire' place names: '-shyre' for neutral voices, '-sher' for British-accented ones) and '_dialect' (an accent's
spoken tics, troll: the -> de, -ing -> -in'). They apply only to the text the engine reads, never to what chat shows.
The guide's other sections (_review, _heard_wrong, ...) serve Living Voices' speech checks and are not carried.
"""
import argparse, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
# which of our designed voices are British-accented (DESIGN: human man Northern English, human woman London, blood
# elves southern English, Forsaken British, dwarves Scottish): they say '-sher', the rest '-shyre'
BRITISH = ['human', 'bloodelf', 'undead', 'dwarf']

def lua(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    a = argparse.ArgumentParser()
    a.add_argument('--guide', default=os.path.expanduser('~/Projects/LivingVoices/data/pronounce.json'))
    a.add_argument('--addon', default=os.path.join(HERE, '..', 'addon', 'CompanionVoice'))
    o = a.parse_args()
    g = json.load(open(o.guide))
    words = g.get('words', {})
    out = ['-- Generated by tools/build_pronounce.py from Living Voices\' pronunciation guide (data/pronounce.json).',
           '-- Do not edit by hand: change the guide and rebuild.', 'CompanionVoicePronounce = {', '  words = {']
    for k in sorted(words):
        out.append(f'    [{lua(k)}] = {lua(words[k])},')
    out.append('  },')
    suf = g.get('_suffix', {})
    out.append('  suffix = {')
    for s, r in sorted(suf.items()):
        r = r if isinstance(r, dict) else {'neutral': r}
        out.append(f'    [{lua(s)}] = {{ neutral = {lua(r.get("neutral", s))}, british = {lua(r.get("british", r.get("neutral", s)))} }},')
    out.append('  },')
    out.append('  british = { ' + ', '.join(f'{x} = true' for x in BRITISH) + ' },')
    out.append('  dialect = {')
    for name, d in sorted(g.get('_dialect', {}).items()):
        if name.startswith('_'): continue
        dw = ', '.join(f'[{lua(k)}] = {lua(v)}' for k, v in sorted(d.get('words', {}).items()))
        out.append(f'    {name} = {{ words = {{ {dw} }}, ing = {"true" if d.get("ing") else "false"} }},')
    out += ['  },', '}', '']
    path = os.path.join(o.addon, 'Pronounce.lua')
    open(path, 'w').write('\n'.join(out))
    print(f'{len(words)} respellings, {len(suf)} suffix rule(s), dialects: '
          f'{[k for k in g.get("_dialect", {}) if not k.startswith("_")]} -> {path}')

if __name__ == '__main__':
    main()
